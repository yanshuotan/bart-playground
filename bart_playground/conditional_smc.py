"""Conditional annealed SMC / Particle Gibbs with original Default mutations.

Fixed Feynman--Kac model: M0=p0, Gj(x)=L(x)**(beta[j+1]-beta[j]),
followed by a pi_beta[j+1]-invariant Default kernel. Its terminal marginal
is the posterior if those kernels are invariant. Default's original numerical
variance floor is inherited, not silently removed. No additional leaf sweep.

The pilot fixes both beta and resampling schedules BEFORE this Markov chain.
Conditional multinomial resampling fixes particle 0 and its ancestor to 0;
the remaining ancestors are independent categorical draws. Simply replacing a
systematically resampled particle by a reference would NOT be this algorithm.
See Andrieu, Doucet & Holenstein (2010), doi:10.1111/j.1467-9868.2009.00736.x.
"""
from dataclasses import dataclass
from pathlib import Path
import pickle

import numpy as np

from .smc import (SMCBART, _copy_particle, _transport_particle, _restore_particle,
                  _normalize_log_weights, _effective_sample_size)
from .bart import _ConstantTemperature


@dataclass
class _Path:
    state: object
    parent: object = None


def _multinomial_ancestors(log_weights, rng, conditional):
    weights = np.exp(log_weights)
    n = len(weights)
    ancestors = np.empty(n, dtype=int)
    start = int(conditional)
    if conditional:
        ancestors[0] = 0
    ancestors[start:] = rng.choice(n, size=n-start, p=weights)
    return ancestors


class ConditionalSMCBART(SMCBART):
    """One selected terminal state per Particle Gibbs iteration, NOT N draws.

    N and mutation count retain the old SMC settings. Unless explicit betas
    are supplied, an independent ordinary SMC pilot fixes beta/resampling
    schedules. No particle/temperature adaptation occurs inside Particle Gibbs.
    n_jobs must be 1: parallel independent chains in the experiment runner.
    """
    def __init__(self, n_particles=50, n_mcmc_steps=2, resampling_schedule=None,
                 pilot_seed=1729, **kwargs):
        if kwargs.get('ndpost',1)!=1:
            raise ValueError('Conditional SMC exposes one endpoint; use repeated step() calls for draws.')
        kwargs['ndpost']=1
        super().__init__(n_particles=n_particles,n_mcmc_steps=n_mcmc_steps,**kwargs)
        if self.n_jobs != 1:
            raise ValueError('Conditional SMC is serial within a chain; parallelize independent chains.')
        self.resampling_schedule = resampling_schedule
        self.pilot_seed = pilot_seed

    def fit_with_data(self, data, quietly=False):
        self.is_fitted=False
        self.trace=[]
        self.particles_=[]
        self.weights_=np.empty(0)
        self.reference_path_=None
        self._validate_data(data.X,data.y)
        self.data = data
        self.sampler.add_data(data)
        self.sampler.add_thresholds(self.preprocessor.thresholds)
        self.sampler.global_prior.fit_hyperparameters(data)
        # The base TemperatureSchedule stores a lambda, which pickle cannot
        # serialize. one_iter still receives its explicit 1/beta argument.
        self.sampler.temp_schedule=_ConstantTemperature(1.)
        self.pilot_diagnostics_ = []
        self.variance_floor_hits_=0
        self.minimum_mutation_variance_=np.inf
        if self.betas is None:
            params = self.get_params()
            keys=('n_trees','tree_alpha','tree_beta','f_k','eps_q','eps_nu',
                  'specification','proposal_probs','max_bins','fixed_eps_sigma2',
                  'quick_decay','ess_target','resample_threshold','max_stages',
                  'max_prior_attempts')
            pilot=SMCBART(n_particles=self.n_particles,n_mcmc_steps=self.n_mcmc_steps,
                          random_state=self.pilot_seed,**{k:params[k] for k in keys})
            pilot.preprocessor=self.preprocessor
            pilot.fit_with_data(data,quietly=quietly)
            self.beta_history_=pilot.beta_history_.copy()
            self.pilot_diagnostics_=pilot.stage_diagnostics_
            mask=[s['resampled'] for s in pilot.stage_diagnostics_]
        else:
            self.beta_history_=self.betas.tolist()
            mask=[True]*(len(self.beta_history_)-1)
        if self.resampling_schedule is not None:
            mask=list(self.resampling_schedule)
        if len(mask)!=len(self.beta_history_)-1 or any(type(x) not in (bool,np.bool_) for x in mask):
            raise ValueError('resampling_schedule must have one Boolean per fixed temperature increment.')
        self.fixed_resampling_=mask
        self.reference_path_=None
        self.iteration_=0
        self.last_diagnostics_=None
        # Initial selected trajectory is generated by the SAME fixed model.
        self._sweep(conditional=False)
        self.is_fitted=True
        return self

    def _sweep(self, conditional=True):
        self.variance_floor_hits_=getattr(self,'variance_floor_hits_',0)
        self.minimum_mutation_variance_=getattr(self,'minimum_mutation_variance_',np.inf)
        rng=self.sampler.generator
        n=self.n_particles
        reference=self.reference_path_ if conditional else None
        particles=[]
        paths=[]
        for i in range(n):
            state=(_restore_particle(reference[0],self.data.X) if reference is not None and i==0
                   else self._sample_prior_state())
            particles.append(state)
            paths.append(_Path(_transport_particle(state)))
        log_weights=np.full(n,-np.log(n))
        diagnostics=[]
        for j,(old_beta,beta) in enumerate(zip(self.beta_history_[:-1],self.beta_history_[1:])):
            log_weights,_=_normalize_log_weights(log_weights+(beta-old_beta)*self._log_likelihoods(particles))
            ess=_effective_sample_size(log_weights)
            if self.fixed_resampling_[j]:
                ancestors=_multinomial_ancestors(log_weights,rng,reference is not None)
                log_weights=np.full(n,-np.log(n))
            else:
                ancestors=np.arange(n)
            next_particles=[]
            next_paths=[]
            for i,a in enumerate(ancestors):
                if reference is not None and i==0:
                    state=_restore_particle(reference[j+1],self.data.X)
                else:
                    state=_copy_particle(particles[a])
                    for _ in range(self.n_mcmc_steps):
                        state=self.sampler.one_iter(state,temp=1/beta)
                        variance=float(state.global_params['eps_sigma2'][0])
                        self.minimum_mutation_variance_=min(self.minimum_mutation_variance_,variance)
                        self.variance_floor_hits_+=int(variance<=1e-8)
                        self.sampler.accepted_moves_logmh.clear()
                next_particles.append(state)
                next_paths.append(_Path(_transport_particle(state),paths[a]))
            particles,paths=next_particles,next_paths
            diagnostics.append({'beta':beta,'ess':ess,'resampled':bool(self.fixed_resampling_[j])})
        index=int(rng.choice(n,p=np.exp(log_weights)))
        node=paths[index]
        selected=[]
        while node is not None:
            selected.append(node.state)
            node=node.parent
        self.reference_path_=list(reversed(selected))
        self.trace=[_copy_particle(self.reference_path_[-1],compress=True)]
        for tree in self.trace[0].trees:
            tree.dataX=self.data.X
        self.sampler.trace=self.trace
        self.particles_=self.trace
        self.weights_=np.ones(1)
        self.last_diagnostics_={'selected_particle':index,'reference_retained':bool(reference is not None and index==0),
                                'stages':diagnostics}
        self.stage_diagnostics_=diagnostics
        if conditional:
            self.iteration_+=1
        return self.trace[0]

    def step(self):
        """One conditional SMC sweep; return the selected cache-free endpoint."""
        if not self.is_fitted:
            raise ValueError('Fit before conditional SMC updates.')
        return self._sweep(conditional=True)

    def get_params(self):
        return {**super().get_params(),'model_type':'ConditionalSMCBART',
                'pilot_seed':self.pilot_seed,'conditional_resampling':'multinomial',
                'posterior_draws_per_iteration':1}

    def sample_posterior(self,*args,**kwargs):
        raise NotImplementedError('Use step(): the auxiliary particle population is not the Particle Gibbs output.')

    def iter_posterior_populations(self,*args,**kwargs):
        raise NotImplementedError('Use step(): conditional SMC selects one endpoint per iteration.')

    def initialize_posterior_chain(self,*args,**kwargs):
        raise NotImplementedError('Conditional SMC is already a Markov-chain kernel; use step().')

    def save_checkpoint(self,path):
        path=Path(path)
        temporary=path.with_suffix('.tmp')
        with temporary.open('wb') as stream:
            pickle.dump(self,stream,protocol=pickle.HIGHEST_PROTOCOL)
        temporary.replace(path)
